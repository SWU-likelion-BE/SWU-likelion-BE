-- 기본 질문 템플릿. 인터뷰 시작 시 interview_question으로 복사된다.
create table interview_question_template (
                                             id bigint generated by default as identity primary key,
                                             template_key varchar(50) not null unique,
                                             topic varchar(30) not null,
                                             content text not null,
                                             sequence integer not null unique,
                                             required boolean not null,
                                             active boolean not null default true
);

-- 업무당 인터뷰 세션 1개
create table interview_session (
                                   id bigint generated by default as identity primary key,
                                   project_id bigint not null references handover_project(id),
                                   task_id bigint not null unique references handover_task(id),
                                   status varchar(20) not null check (status in ('IN_PROGRESS', 'CONFIRMED')),
                                   created_by bigint not null references app_user(id),
                                   created_at timestamptz not null,
                                   updated_at timestamptz not null
);
create index ix_interview_session_project on interview_session(project_id);

-- 세션별 질문. BASE는 템플릿에서 복사, FOLLOW_UP은 AI 추가 질문(#20)
create table interview_question (
                                    id bigint generated by default as identity primary key,
                                    session_id bigint not null references interview_session(id),
                                    type varchar(20) not null check (type in ('BASE', 'FOLLOW_UP')),
                                    template_key varchar(50),
                                    topic varchar(30) not null,
                                    content text not null,
                                    parent_question_id bigint references interview_question(id),
                                    source_answer_revision_id bigint,
                                    sequence integer not null,
                                    required boolean not null,
                                    created_at timestamptz not null,
                                    unique (session_id, sequence),
                                    check ((type = 'BASE' and template_key is not null and parent_question_id is null)
                                        or (type = 'FOLLOW_UP' and parent_question_id is not null))
);

-- 질문당 답변 1개. 내용은 answer_revision에 쌓고 최신 버전만 가리킨다
create table interview_answer (
                                  id bigint generated by default as identity primary key,
                                  question_id bigint not null unique references interview_question(id),
                                  author_id bigint not null references app_user(id),
                                  current_revision_id bigint,
                                  created_at timestamptz not null,
                                  updated_at timestamptz not null
);

-- 원본 답변의 모든 버전. 수정 시 덮어쓰지 않고 새 행을 추가한다
create table answer_revision (
                                 id bigint generated by default as identity primary key,
                                 answer_id bigint not null references interview_answer(id),
                                 revision_no integer not null check (revision_no >= 1),
                                 raw_text text not null check (length(trim(raw_text)) > 0),
                                 created_by bigint not null references app_user(id),
                                 created_at timestamptz not null,
                                 unique (answer_id, revision_no)
);

alter table interview_answer
    add constraint fk_interview_answer_current_revision
        foreign key (current_revision_id) references answer_revision(id);
alter table interview_question
    add constraint fk_interview_question_source_revision
        foreign key (source_answer_revision_id) references answer_revision(id);

-- 확정 기록. 확정할 때마다 그 시점의 답변 버전 목록을 고정한다
create table interview_confirmation (
                                        id bigint generated by default as identity primary key,
                                        session_id bigint not null references interview_session(id),
                                        confirmed_by bigint not null references app_user(id),
                                        confirmed_at timestamptz not null
);
create index ix_interview_confirmation_session on interview_confirmation(session_id, id);

create table interview_confirmation_item (
                                             confirmation_id bigint not null references interview_confirmation(id),
                                             answer_revision_id bigint not null references answer_revision(id),
                                             primary key (confirmation_id, answer_revision_id)
);

