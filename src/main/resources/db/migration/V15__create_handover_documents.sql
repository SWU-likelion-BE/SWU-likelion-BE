create table handover_document (
    id bigint generated by default as identity primary key,
    task_id bigint not null unique references handover_task(id),
    created_at timestamptz not null
);

create table handover_document_version (
    id bigint generated by default as identity primary key,
    document_id bigint not null references handover_document(id),
    confirmation_id bigint not null references interview_confirmation(id),
    generation_job_id varchar(255) not null unique,
    status varchar(20) not null check (status in ('DRAFT', 'PUBLISHED')),
    title varchar(255) not null,
    revision bigint not null check (revision >= 0),
    created_at timestamptz not null,
    updated_at timestamptz not null
);

create index ix_handover_document_version_document on handover_document_version(document_id);

create table handover_document_section (
    id bigint generated by default as identity primary key,
    version_id bigint not null references handover_document_version(id),
    type varchar(255) not null,
    title varchar(255) not null,
    content text not null,
    position integer not null check (position >= 0),
    unique (version_id, position) deferrable initially deferred
);
