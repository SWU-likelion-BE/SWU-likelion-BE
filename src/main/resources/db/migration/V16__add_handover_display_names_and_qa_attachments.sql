alter table handover_project
    add column organization_name varchar(255),
    add column affiliation_name varchar(255);

alter table handover_document_version add column published_at timestamptz;

create table qa_attachment (
    id bigint generated by default as identity primary key,
    thread_id bigint not null references qa_thread(id),
    original_filename varchar(255) not null,
    content_type varchar(255) not null,
    size_bytes bigint not null check (size_bytes between 1 and 10485760),
    content bytea not null check (octet_length(content) = size_bytes),
    created_at timestamptz not null
);
create index ix_qa_attachment_thread on qa_attachment(thread_id, id);
