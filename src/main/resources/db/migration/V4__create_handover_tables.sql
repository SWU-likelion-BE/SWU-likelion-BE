create table organization(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES  app_user (id)
);

create table organization_member(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES  organization (id),
    user_id BIGINT NOT NULL REFERENCES app_user (id),
    organization_role VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    CONSTRAINT uk_organization_member_organization_user
                                UNIQUE  (organization_id, user_id)
);

create table handover_project(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES organization(id),
    title VARCHAR(255) NOT NULL,
    role_name VARCHAR(255) NOT NULL,
    dead_line DATE NOT NULL
);

create table project_participant(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL REFERENCES handover_project (id),
    member_id BIGINT NOT NULL REFERENCES organization_member (id),
    role VARCHAR(255) NOT NULL,
    CONSTRAINT uk_project_participant_project_member_role
                                UNIQUE (project_id, member_id, role)
);