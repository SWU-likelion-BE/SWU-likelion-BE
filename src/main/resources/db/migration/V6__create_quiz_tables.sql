create table quiz_set (
    id bigint generated by default as identity primary key,
    project_id bigint not null references handover_project(id),
    -- Document tables are owned by the document module and not available yet.
    version_id bigint not null,
    passing_score integer not null check (passing_score between 70 and 100)
);
create index ix_quiz_set_project on quiz_set(project_id, id);

create table quiz_question (
    id bigint generated by default as identity primary key,
    quiz_set_id bigint not null references quiz_set(id),
    sequence integer not null check (sequence > 0),
    stem text not null,
    correct_option integer not null check (correct_option >= 0),
    explanation text not null,
    section_id bigint not null,
    topic varchar(255) not null,
    unique (quiz_set_id, sequence)
);
create table quiz_option (
    question_id bigint not null references quiz_question(id),
    option_index integer not null,
    content text not null,
    primary key (question_id, option_index)
);
create table quiz_attempt (
    id bigint generated by default as identity primary key,
    quiz_set_id bigint not null references quiz_set(id),
    user_id bigint not null references app_user(id),
    attempt_no integer not null check (attempt_no > 0),
    started_at timestamptz not null,
    submitted_at timestamptz,
    next_allowed_at timestamptz,
    correct_count integer,
    total_count integer,
    score integer check (score between 0 and 100),
    passed boolean,
    unique (quiz_set_id, user_id, attempt_no)
);
create unique index uk_quiz_attempt_open on quiz_attempt(quiz_set_id, user_id) where submitted_at is null;
create table quiz_response (
    attempt_id bigint not null references quiz_attempt(id),
    question_id bigint not null references quiz_question(id),
    selected_option integer not null check (selected_option >= 0),
    primary key (attempt_id, question_id)
);
