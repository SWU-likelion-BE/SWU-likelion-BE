create table qa_thread (
    id bigint generated by default as identity primary key,
    project_id bigint not null references handover_project(id),
    -- Document module will add version/section foreign keys when its tables exist.
    version_id bigint not null,
    section_id bigint not null,
    author_id bigint not null references app_user(id),
    content text not null check (length(btrim(content)) between 1 and 10000),
    status varchar(20) not null check (status in ('OPEN', 'RESOLVED')),
    revision integer not null check (revision > 0),
    reply_count integer not null check (reply_count >= 0),
    created_at timestamptz not null,
    updated_at timestamptz not null
);
create index ix_qa_thread_project_status on qa_thread(project_id, status, id);
create index ix_qa_thread_project on qa_thread(project_id, id);

create table qa_reply (
    id bigint generated by default as identity primary key,
    thread_id bigint not null references qa_thread(id),
    author_id bigint not null references app_user(id),
    content text not null check (length(btrim(content)) between 1 and 10000),
    question_revision integer not null check (question_revision > 0),
    question_content text not null,
    created_at timestamptz not null
);
create index ix_qa_reply_thread on qa_reply(thread_id, id);

create table qa_outbox_event (
    id bigint generated by default as identity primary key,
    type varchar(30) not null check (type in ('QUESTION_CREATED', 'ANSWER_CREATED')),
    project_id bigint not null references handover_project(id),
    thread_id bigint not null references qa_thread(id),
    reply_id bigint references qa_reply(id),
    actor_id bigint not null references app_user(id),
    dedupe_key varchar(255) not null unique,
    created_at timestamptz not null,
    processed_at timestamptz,
    check ((type = 'QUESTION_CREATED' and reply_id is null) or (type = 'ANSWER_CREATED' and reply_id is not null))
);
create index ix_qa_outbox_pending on qa_outbox_event(id) where processed_at is null;
