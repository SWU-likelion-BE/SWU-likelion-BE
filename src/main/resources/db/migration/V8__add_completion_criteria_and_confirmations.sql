create table completion_criteria (
    project_id bigint primary key references handover_project(id),
    minimum_completeness integer not null default 80 check (minimum_completeness between 80 and 100),
    quiz_passing_score integer not null default 70 check (quiz_passing_score between 70 and 100),
    revision bigint not null default 0 check (revision >= 0),
    updated_by bigint references app_user(id),
    updated_at timestamptz
);

create table completion_confirmation (
    id bigint generated by default as identity primary key,
    project_id bigint not null references handover_project(id),
    member_id bigint not null references organization_member(id),
    role varchar(30) not null check (role in ('PREDECESSOR', 'SUCCESSOR')),
    criteria_revision bigint not null check (criteria_revision >= 0),
    confirmed_at timestamptz not null,
    unique (project_id, member_id, role, criteria_revision),
    foreign key (project_id, member_id, role) references project_participant(project_id, member_id, role)
);
create index ix_completion_confirmation_current on completion_confirmation(project_id, criteria_revision);

