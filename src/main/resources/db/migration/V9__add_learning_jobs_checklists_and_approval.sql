alter table handover_project add column approved_by bigint references app_user(id);

create table checklist_completion (
    id bigint generated by default as identity primary key,
    project_id bigint not null references handover_project(id),
    document_id bigint not null,
    version_id bigint not null,
    item_id bigint not null,
    user_id bigint not null references app_user(id),
    completed boolean not null,
    updated_at timestamptz not null,
    unique (project_id, item_id, user_id)
);
create index ix_checklist_completion_project on checklist_completion(project_id, completed);

create table quiz_generation_job (
    id bigint generated by default as identity primary key,
    project_id bigint not null references handover_project(id),
    document_id bigint not null,
    version_id bigint not null,
    requested_by bigint not null references app_user(id),
    request_key varchar(100) not null,
    passing_score integer not null check (passing_score between 70 and 100),
    status varchar(20) not null check (status in ('QUEUED','RUNNING','SUCCEEDED','FAILED')),
    attempt_count integer not null check (attempt_count >= 0),
    created_at timestamptz not null,
    started_at timestamptz,
    finished_at timestamptz,
    quiz_set_id bigint references quiz_set(id),
    error_code varchar(100),
    provider varchar(255), model varchar(255), prompt_version varchar(255),
    unique (project_id, request_key)
);
create index ix_quiz_generation_pending on quiz_generation_job(status, id);
create table quiz_generation_source (
    job_id bigint not null references quiz_generation_job(id),
    source_position integer not null,
    section_id bigint not null,
    type varchar(255) not null,
    content text not null,
    primary key (job_id, source_position),
    unique (job_id, section_id)
);

create table completion_workflow (
    project_id bigint primary key references handover_project(id),
    status varchar(20) not null check (status in ('REQUESTED','APPROVED')),
    requested_by bigint not null references app_user(id),
    requested_at timestamptz not null,
    approved_by bigint references app_user(id),
    approved_at timestamptz,
    check ((status = 'REQUESTED' and approved_by is null and approved_at is null)
        or (status = 'APPROVED' and approved_by is not null and approved_at is not null))
);
create table completion_audit (
    id bigint generated by default as identity primary key,
    project_id bigint not null references handover_project(id),
    action varchar(20) not null check (action in ('REQUESTED','APPROVED')),
    actor_id bigint not null references app_user(id),
    score integer not null check (score between 0 and 100),
    minimum_completeness integer not null check (minimum_completeness between 80 and 100),
    quiz_passing_score integer not null check (quiz_passing_score between 70 and 100),
    occurred_at timestamptz not null,
    unique (project_id, action)
);
